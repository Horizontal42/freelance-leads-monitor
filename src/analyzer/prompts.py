def detect_non_it_direction(order: RawOrder) -> str:
    """Определить код прикладного направления по тегам или тексту вакансии."""
    for tag in (order.tags or []):
        if tag.startswith("direction:"):
            d = tag.split(":", 1)[1]
            if d in DIRECTION_PROFILES:
                return d

    text = f"{order.title}\n{order.description}".lower()
    if any(k in text for k in ["чпу", "fanuc", "фанук", "токарн", "фрезерн", "autocut", "эрози"]):
        return "cnc"
    if any(k in text for k in ["ноутбук", "модульн", "матриц", "компьютерн", "ремонт пк", "сервисн"]):
        return "electronics_repair"
    if any(k in text for k in ["helpdesk", "хэлпдеск", "эникей", "поддержк", "витая пара"]):
        return "helpdesk_l1"
